#!/usr/bin/env python3
"""Generate factual element/isotope masses from the pinned RDKit table.
Source: https://github.com/rdkit/rdkit/tree/Release_2026_03_6/Code/GraphMol
No RDKit runtime is linked into DuckSMILES or the Apple app.
"""
from pathlib import Path
import rdkit
from rdkit import Chem
assert rdkit.__version__ == '2026.03.6'
t=Chem.GetPeriodicTable()
lines=['// Generated by tasks/benchmarks/generate_mass_data.py using RDKit 2026.03.6.',
       '// Element symbols, average weights, and isotope masses; numerical reference data.',
       'pub const ELEMENTS: [(&str, f64, f64); 118] = [']
for z in range(1,119):
    lines.append(f'    ("{t.GetElementSymbol(z)}", {float(t.GetAtomicWeight(z))!r}, {float(t.GetMostCommonIsotopeMass(z))!r}),')
lines+= ['];','pub const ISOTOPES: &[(u8, u16, f64)] = &[']
count=0
for z in range(1,119):
    for isotope in range(1,401):
        mass=float(t.GetMassForIsotope(z,isotope))
        if mass>0:
            lines.append(f'    ({z}, {isotope}, {mass!r}),');count+=1
lines+= ['];','']
path=Path(__file__).resolve().parents[2]/'crates/smiles/src/periodic_data.rs'
path.write_text('\n'.join(lines));print(f'{path}: 118 elements, {count} isotope masses')
