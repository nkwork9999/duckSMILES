"""Pin RDKit's registered functional-group definitions and independent literals."""
import csv
import hashlib
import json
from pathlib import Path

import rdkit
from rdkit import Chem, RDConfig, RDLogger
from rdkit.Chem import Descriptors

assert rdkit.__version__ == '2026.03.6'
RDLogger.DisableLog('rdApp.*')
source = Path(RDConfig.RDDataDir) / 'FragmentDescriptors.csv'
registered = dict(Descriptors._descList)
patterns = {}
for row in csv.reader(source.read_text().splitlines(), delimiter='\t', quoting=csv.QUOTE_NONE):
    if not row or row[0].startswith('#') or len(row) < 3:
        continue
    id = row[0].replace('=', '_').replace('-', '_')
    description = row[1].replace('"', '')
    title = description.removeprefix('Number of ')
    title = title[:1].upper() + title[1:]
    patterns[id] = dict(id=id, title=title, description=description, smarts=row[2],
                        group='Functional groups', unit='', digits=0,
                        origin='rdkit-standard', verification='pending-expanded-validation')
assert len(patterns) == 85 and all(id in registered for id in patterns)
# Clarify terse/overlapping upstream titles without changing SMARTS definitions.
for id, title in {'fr_COO': 'Carboxylic acids (C-linked)', 'fr_COO2': 'Carboxylic acids (general)',
                  'fr_NH2': 'NH₂ nitrogens', 'fr_NH1': 'NH nitrogens', 'fr_NH0': 'Nitrogens without H',
                  'fr_Ar_COO': 'Aromatic carboxylic acids', 'fr_piperdine': 'Piperidine rings',
                  'fr_piperzine': 'Piperazine rings', 'fr_C_O': 'Carbonyl groups',
                  'fr_C_O_noCOO': 'Carbonyls excluding COOH'}.items():
    patterns[id]['title'] = title
rows = [patterns[id] for id in sorted(patterns)]
manifest = dict(schema=1, rdkit=rdkit.__version__,
                source='RDKit Data/FragmentDescriptors.csv',
                source_url='https://github.com/rdkit/rdkit/blob/Release_2026_03_6/Data/FragmentDescriptors.csv',
                source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                count=len(rows), descriptors=rows)
Path('tasks/descriptors/fragment-patterns.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
rust = '// Copyright (C) 2002 Rational Discovery LLC; RDKit BSD-3-Clause data.\n'
rust += '// See RDKIT-DATA-LICENSE.txt. Generated by tasks/descriptors/generate_fragments.py.\n'
rust += 'pub(crate) const PATTERNS: &[(&str, &str)] = &[\n'
for row in rows:
    rust += f'    ("{row["id"]}", r###"{row["smarts"]}"###),\n'
rust += '];\n'
Path('crates/smiles/src/fragment_patterns.rs').write_text(rust)

params = Chem.SmilesParserParams()
params.removeHs = False
queries = {id: Chem.MolFromSmarts(row['smarts']) for id, row in patterns.items()}
assert all(q is not None for q in queries.values())
fixtures = [line.split('\t')[0] for line in Path('crates/smiles/tests/fixtures/descriptor_phase1.tsv').read_text().splitlines() if not line.startswith('#')]
fixtures += ['CC(=O)O','CC(=O)[O-]','CC(=O)OCC','CC=O','COC','CC(=O)N',
             'NC(=O)N','CN(C)C','C[N+](C)(C)C','Oc1ccccc1','Oc1ccccc1O',
             'CS(C)(=O)=O','CS(=O)(=O)N','COP(=O)(O)O','OP(=O)(O)O',
             'N=[N+]=[N-]','C[N-][N+]#N','CC#N','CC#C','CCC=C','COC(=O)NC',
             'CN1C(=O)CN=C(c2ccccc2)c2cc(Cl)ccc21','N1C(=O)CC1','C1CCNCC1','C1CNCCN1',
             'C1COCCN1','CC(=O)CC(=O)C','O=C1NC(=O)NC(=O)C1','c1nnn[nH]1',
             'CC(=NO)C','CC=NNC','CCNCCN','CCOC(=O)NCC','[H]OC','[H]N(C)C',
             '[H]C(O)(C)C','[H][O+](C)C']
fixtures = list(dict.fromkeys(fixtures))
covered = set()
for smiles in fixtures:
    mol = Chem.MolFromSmiles(smiles, params)
    assert mol is not None, smiles
    covered.update(id for id, q in queries.items() if mol.HasSubstructMatch(q))
missing = set(patterns) - covered
nci = Path(RDConfig.RDDataDir) / 'NCI' / 'first_5K.smi'
for line in nci.read_text().splitlines():
    if not missing:
        break
    smiles = line.split()[0]
    mol = Chem.MolFromSmiles(smiles, params)
    if mol is None or mol.GetNumAtoms() > 128:
        continue
    found = {id for id in missing if mol.HasSubstructMatch(queries[id])}
    if found:
        fixtures.append(smiles)
        missing -= found
assert not missing, sorted(missing)
out = ['# RDKit 2026.03.6 registered fragments; removeHs=False, uniquify=True, maxMatches=1000']
for smiles in fixtures:
    mol = Chem.MolFromSmiles(smiles, params)
    for id in sorted(patterns):
        out.append(f'{smiles}\t{id}\t{registered[id](mol)}')
Path('crates/smiles/tests/fixtures/descriptor_fragments.tsv').write_text('\n'.join(out) + '\n')
print(len(rows), 'patterns;', len(fixtures), 'molecules;', len(out)-1, 'golden values; all 85 have positive examples')
