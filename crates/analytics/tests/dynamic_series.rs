#[test]
fn failed_transfer_optimizer_does_not_publish_information_criteria_and_future_inputs_do_not_train()
{
    let rows = (0..44)
        .map(|i| {
            let x = ((i * 19 % 31) as f64 - 15.) / 8.;
            let y = 2. + (i as f64 * 0.2).sin() + 0.7 * x;
            vec![x, y]
        })
        .collect::<Vec<_>>();
    let args = [40., 0., 0., 1., 1., 1., 4., 0.95, 1., 1e-8];
    let j = run("transfer_function_model", &rows, &args).unwrap();
    assert!(j.contains("\"converged\":false"), "{j}");
    assert!(j.contains("\"aic\":null"), "{j}");
    assert!(j.contains("\"bic\":null"), "{j}");
    let mut changed = rows.clone();
    for r in &mut changed[40..] {
        r[0] *= 100.;
        r[1] = 1e200;
    }
    let k = run("transfer_function_model", &changed, &args).unwrap();
    for key in ["denominator", "numerator", "ar", "ma"] {
        check(&values(&j, key), &values(&k, key));
    }
    close(number(&j, "log_likelihood"), number(&k, "log_likelihood"));
}
