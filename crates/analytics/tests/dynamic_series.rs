use ducksmiles_analytics::execute as run;
fn number(j: &str, k: &str) -> f64 {
    let s = j.find(&format!("\"{k}\":")).unwrap() + k.len() + 3;
    j[s..]
        .split([',', '}', ']'])
        .next()
        .unwrap()
        .parse()
        .unwrap()
}
fn values(j: &str, k: &str) -> Vec<f64> {
    let s = j.find(&format!("\"{k}\":[")).unwrap() + k.len() + 4;
    let t = &j[s..];
    let e = t.find(']').unwrap();
    if e == 0 {
        vec![]
    } else {
        t[..e]
            .split(',')
            .map(|x| x.trim().parse().unwrap())
            .collect()
    }
}
fn close(a: f64, b: f64) {
    assert!((a - b).abs() < 1e-8 * (1. + b.abs()), "{a} != {b}")
}
fn check(a: &[f64], b: &[f64]) {
    assert_eq!(a.len(), b.len());
    for (x, y) in a.iter().zip(b) {
        close(*x, *y)
    }
}

#[test]
fn arima_forecast_variance_matches_ar_random_walk_ma_double_integrated_and_seasonal_closed_forms() {
    let rows = vec![vec![10.]; 5];
    let cases = [
        (
            vec![0.95, 2., 1., 0., 0., 1., -0.5, 1.],
            vec![2., 2.5, 2.625, 2.65625, 2.6640625],
        ),
        (
            vec![0.95, 2., 0., 0., 1., 1., 1., 1.],
            vec![2., 4., 6., 8., 10.],
        ),
        (
            vec![0.95, 2., 0., 1., 0., 1., 1., 0.5],
            vec![2., 2.5, 2.5, 2.5, 2.5],
        ),
        (
            vec![0.95, 2., 0., 0., 2., 1., 1., 1., 1.],
            vec![2., 10., 28., 60., 110.],
        ),
        (
            vec![0.95, 2., 0., 0., 1., 1., 1., 2.],
            vec![2., 2., 4., 4., 6.],
        ),
    ];
    for (a, w) in cases {
        let j = run("arima_forecast_intervals", &rows, &a).unwrap();
        check(&values(&j, "forecast_variances"), &w);
        let lo = values(&j, "lower");
        let hi = values(&j, "upper");
        for i in 0..5 {
            close(lo[i] + hi[i], 20.);
        }
    }
}
#[test]
fn ccf_has_explicit_input_leads_sign_and_swap_lag_symmetry() {
    let rows = vec![vec![1., 0.], vec![0., 1.], vec![-1., 0.], vec![0., -1.]];
    let j = run("cross_correlation", &rows, &[2.]).unwrap();
    check(&values(&j, "correlations"), &[0., -0.5, 0., 1., 0.]);
    let swap = rows.iter().map(|r| vec![r[1], r[0]]).collect::<Vec<_>>();
    let k = run("cross_correlation", &swap, &[2.]).unwrap();
    let mut a = values(&k, "correlations");
    a.reverse();
    check(&a, &values(&j, "correlations"));
}
